#!/usr/bin/env bash
# Regenerates schema.{postgres,mysql,sqlite}.sql: the SQL Better Auth 1.7.8's own CLI
# (`npx auth generate`) writes for auth.ts against an empty Postgres 17, MySQL 8.4 and SQLite
# database. Runs everything in Docker containers; needs nothing but Docker.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
net="fastauth-ba-schema-$$"
pg="fastauth-ba-pg-$$"
my="fastauth-ba-mysql-$$"
work="$(mktemp -d)"
cleanup() {
  docker rm -f "$pg" "$my" >/dev/null 2>&1 || true
  docker network rm "$net" >/dev/null 2>&1 || true
  rm -rf "$work"
}
trap cleanup EXIT
cp "$here/auth.ts" "$here/package.json" "$work/"
docker network create "$net" >/dev/null
docker run -d --rm --name "$pg" --network "$net" -e POSTGRES_PASSWORD=ci postgres:17 >/dev/null
docker run -d --rm --name "$my" --network "$net" -e MYSQL_ROOT_PASSWORD=ci -e MYSQL_DATABASE=ba mysql:8.4 >/dev/null
for _ in $(seq 1 60); do docker exec "$pg" pg_isready -h 127.0.0.1 -U postgres >/dev/null 2>&1 && break; sleep 1; done
for _ in $(seq 1 180); do
  docker exec "$my" mysql --protocol=tcp -h127.0.0.1 -uroot -pci -e 'SELECT 1' >/dev/null 2>&1 && break
  sleep 1
done
docker run --rm --network "$net" --user "$(id -u):$(id -g)" -e HOME=/tmp -v "$work":/app -w /app node:24 sh -ec '
  npm install --no-audit --no-fund --silent
  BA_DB=postgres DATABASE_URL=postgres://postgres:ci@'"$pg"':5432/postgres \
    npx auth generate --config auth.ts --output schema.postgres.sql --yes
  BA_DB=mysql DATABASE_URL=mysql://root:ci@'"$my"':3306/ba \
    npx auth generate --config auth.ts --output schema.mysql.sql --yes
  BA_DB=sqlite DATABASE_URL=/app/empty.sqlite \
    npx auth generate --config auth.ts --output schema.sqlite.sql --yes
'
for db in postgres mysql sqlite; do
  { echo "-- Generated by Better Auth 1.7.8 (\`npx auth generate\`) for auth.ts on $db (see generate.sh)."
    cat "$work/schema.$db.sql"; } > "$here/schema.$db.sql"
done
echo "wrote $here/schema.{postgres,mysql,sqlite}.sql"
