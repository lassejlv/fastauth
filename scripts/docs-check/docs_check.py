#!/usr/bin/env python3
"""Compiles the Rust blocks in docs/ against the workspace crates. See README.md.

    docs_check.py generate [--docs DIR] [--out DIR]   write the scratch crate
    docs_check.py verify   [--docs DIR] [--out DIR]   doc lines present verbatim, excerpts match core
    docs_check.py annotate [--out DIR]                 stdin filter: map compiler spans back to docs lines
"""
import argparse
import difflib
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE))
import templates  # noqa: E402

FENCE = re.compile(r"^```rust[^\n]*\n(.*?)^```[ \t]*$", re.S | re.M)
INCLUDE = re.compile(r"^@(\d*)(?::(\d+)-(\d+))?$")
CORE_SRC = REPO / "crates" / "fastauth-core" / "src"


class Block:
    def __init__(self, page, ordinal, line, text):
        self.page, self.ordinal, self.line = page, ordinal, line
        self.lines = text.rstrip("\n").split("\n")
        self.first = self.lines[0].strip()


def docs_label(docs):
    try:
        return str(docs.resolve().relative_to(Path.cwd().resolve()))
    except ValueError:
        return str(docs)


def read_blocks(docs):
    pages = {}
    for md in sorted(docs.rglob("*.md")):
        page = md.relative_to(docs).as_posix()
        text = md.read_text()
        for i, m in enumerate(FENCE.finditer(text), 1):
            pages.setdefault(page, []).append(Block(page, i, text.count("\n", 0, m.start()) + 1, m.group(1)))
    return pages


def match(docs):
    """Pairs every docs block with its template entry by first line, in page order.

    Returns ({page: [(block, entry)]}, problems)."""
    label = docs_label(docs)
    pages = read_blocks(docs)
    matched, problems = {}, []
    for page in sorted(set(pages) | set(templates.PAGES)):
        blocks = pages.get(page, [])
        entries = templates.PAGES[page].blocks if page in templates.PAGES else []
        sm = difflib.SequenceMatcher(None, [e.first for e in entries], [b.first for b in blocks], autojunk=False)
        pairs = matched.setdefault(page, [])
        for tag, a1, a2, b1, b2 in sm.get_opcodes():
            if tag == "equal":
                pairs += zip(blocks[b1:b2], entries[a1:a2])
                continue
            for b in blocks[b1:b2]:
                problems.append(
                    f"{label}/{page}:{b.line} has no template; add one in scripts/docs-check/templates.py "
                    f"under {page!r} (first line: {b.first!r})"
                )
            for e in entries[a1:a2]:
                problems.append(
                    f"scripts/docs-check/templates.py: {page!r} entry {e.first!r} matches no block on the page "
                    f"(block edited, moved or removed?)"
                )
    return matched, problems


def slug(page):
    return re.sub(r"[^a-z0-9]+", "_", page.lower().removesuffix(".md")).strip("_")


def render(page_cfg, pairs, label):
    """Yields (module, file text, line map, blocks it includes) for one page."""
    by_entry = {id(e): b for b, e in pairs}
    entries = page_cfg.blocks

    def expand(tpl, own, out, src, used):
        for line in tpl.strip("\n").split("\n"):
            m = INCLUDE.match(line)
            if not m:
                out.append(line)
                src.append(None)
                continue
            entry = entries[int(m.group(1)) - 1] if m.group(1) else own
            block = by_entry.get(id(entry))
            if block is None:
                raise LookupError(f"{line!r} refers to a template entry with no matching block")
            lo, hi = (int(m.group(2)), int(m.group(3))) if m.group(2) else (1, len(block.lines))
            for k in range(lo, min(hi, len(block.lines)) + 1):
                out.append(block.lines[k - 1])
                src.append(f"{label}/{block.page}:{block.line + k}")
            used.add(id(block))

    def module(name, tpl, own, ctx):
        out, src, used = [], [], set()
        expand(tpl, own, out, src, used)
        head = [f"// Generated by scripts/docs-check from {label}/{page_cfg.path}. Do not edit."]
        head += (page_cfg.base + ctx).rstrip("\n").split("\n") + ["pub mod it {", "use super::*;"]
        lines = head + out + ["}"]
        srcmap = [None] * len(head) + src + [None]
        return name, "\n".join(lines) + "\n", srcmap, used

    if page_cfg.module is not None:
        yield module(slug(page_cfg.path), page_cfg.module, None, page_cfg.ctx)
        return
    for b, e in pairs:
        if e.excerpt:
            continue
        ctx = page_cfg.ctx if e.ctx is None else e.ctx
        yield module(f"{slug(page_cfg.path)}_b{b.ordinal:02d}", e.tpl, e, ctx)


def generate(docs, out):
    label = docs_label(docs)
    matched, problems = match(docs)
    src_dir = out / "src"
    src_dir.mkdir(parents=True, exist_ok=True)
    files, linemap, rendered = {}, {}, {}
    for page, pairs in matched.items():
        if page not in templates.PAGES or not pairs:
            continue
        try:
            for name, text, srcmap, used in render(templates.PAGES[page], pairs, label):
                files[f"{name}.rs"] = text
                linemap[f"src/{name}.rs"] = srcmap
                for u in used:
                    rendered.setdefault(u, []).append(f"src/{name}.rs")
        except LookupError as err:
            problems.append(f"scripts/docs-check/templates.py: {page!r}: {err}")
        for b, e in pairs:
            if not e.excerpt and id(b) not in rendered:
                problems.append(f"{label}/{page}:{b.line} is never included by a template (add @ to its template)")
    mods = sorted(n.removesuffix(".rs") for n in files)
    files["lib.rs"] = templates.LIB + "".join(f"pub mod {m};\n" for m in mods)
    for stale in src_dir.glob("*.rs"):
        if stale.name not in files:
            stale.unlink()
    for name, text in files.items():
        write_if_changed(src_dir / name, text)
    write_if_changed(out / "Cargo.toml", templates.cargo_toml(os.path.relpath(REPO, out)))
    lock = out / "Cargo.lock"
    if not lock.exists():
        lock.write_text((REPO / "Cargo.lock").read_text())
    (out / "linemap.json").write_text(json.dumps(linemap))
    for p in problems:
        print(p)
    count = sum(len(v) for v in matched.values())
    print(f"docs-check: {count} rust blocks matched, {len(mods)} modules written to {out}")
    return 1 if problems else 0


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def norm(line):
    return re.sub(r"\s+", " ", line.strip())


def verify(docs, out):
    label = docs_label(docs)
    matched, _ = match(docs)
    linemap = json.loads((out / "linemap.json").read_text())
    by_loc = {}
    for f, srcmap in linemap.items():
        for loc in srcmap:
            if loc:
                by_loc.setdefault(loc, set()).add(f)
    core = set()
    for f in CORE_SRC.rglob("*.rs"):
        core.update(norm(l) for l in f.read_text().splitlines())
    missing = excerpt_missing = 0
    for page, pairs in matched.items():
        for b, e in pairs:
            if e.excerpt:
                for k, l in enumerate(b.lines, 1):
                    if norm(l) and norm(l) not in core:
                        print(f"{label}/{page}:{b.line + k}: excerpt line not in crates/fastauth-core/src | {l.strip()}")
                        excerpt_missing += 1
                continue
            have = set()
            for f in set().union(*(by_loc.get(f"{label}/{page}:{b.line + k}", set()) for k in range(1, len(b.lines) + 1))):
                have.update(l.strip() for l in (out / f).read_text().splitlines())
            for k, l in enumerate(b.lines, 1):
                if l.strip() and l.strip() not in have:
                    print(f"{label}/{page}:{b.line + k}: doc line not in the generated sources | {l.strip()}")
                    missing += 1
    print(f"docs-check: {missing} doc lines missing from the generated sources, "
          f"{excerpt_missing} excerpt lines missing from crates/fastauth-core/src")
    return 1 if missing or excerpt_missing else 0


def annotate(out):
    linemap = json.loads((out / "linemap.json").read_text())
    span = re.compile(r"(-->|:::)\s+(?:.*?/)?(src/[\w]+\.rs):(\d+):\d+")
    for line in sys.stdin:
        sys.stdout.write(line)
        m = span.search(line)
        if not m or m.group(2) not in linemap:
            continue
        srcmap = linemap[m.group(2)]
        n = int(m.group(3))
        loc = srcmap[n - 1] if n <= len(srcmap) else None
        if loc:
            sys.stdout.write(f"{line[:m.start()]}   = docs: {loc}\n")
        else:
            near = next((s for s in srcmap[n - 1:] if s), None) or next((s for s in reversed(srcmap[:n]) if s), None)
            sys.stdout.write(f"{line[:m.start()]}   = in template scaffolding (near {near})\n")
        sys.stdout.flush()
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["generate", "verify", "annotate"])
    ap.add_argument("--docs", type=Path, default=REPO / "docs")
    ap.add_argument("--out", type=Path, default=REPO / "target" / "docs-check")
    a = ap.parse_args()
    if a.command == "generate":
        return generate(a.docs, a.out)
    if a.command == "verify":
        return verify(a.docs, a.out)
    return annotate(a.out)


if __name__ == "__main__":
    sys.exit(main())
