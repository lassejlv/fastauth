#!/usr/bin/env bash
# Regenerates the fastauth 0.5 databases that crates/fastauth/tests/upgrade_0_5.rs upgrades:
# crates/fastauth/tests/fixtures/upgrade_0_5/<backend>.sql (the dump) and <backend>.json (the
# manifest of passwords, cookies, tokens and ids), for sqlite, postgres and mysql.
#
# Each database is made by fastauth 0.5.0 itself (git tag v0.5.0): its migrator creates the
# schema, and its HTTP API seeds the rows. Postgres 17 and MySQL 8.4 run in throwaway Docker
# containers, named by PG_CONTAINER and MYSQL_CONTAINER, and removed on exit.
#
#   scripts/upgrade-0.5-fixtures/generate.sh [sqlite] [postgres] [mysql]   # default: all three
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
out="$root/crates/fastauth/tests/fixtures/upgrade_0_5"
pg_container="${PG_CONTAINER:-fastauth-upgrade-fixtures-pg}"
mysql_container="${MYSQL_CONTAINER:-fastauth-upgrade-fixtures-mysql}"
backends=("$@")
[ ${#backends[@]} -eq 0 ] && backends=(sqlite postgres mysql)

export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$root/target}"
cargo build --quiet --manifest-path "$here/Cargo.toml"
generator="$CARGO_TARGET_DIR/debug/upgrade-0-5-fixtures"
mkdir -p "$out"
work="$(mktemp -d)"
cleanup() {
  rm -rf "$work"
  docker rm -f "$pg_container" "$mysql_container" >/dev/null 2>&1 || true
}
trap cleanup EXIT

header() {
  printf -- '-- fastauth 0.5.0 database for crates/fastauth/tests/upgrade_0_5.rs (%s).\n' "$1"
  printf -- '-- Generated by scripts/upgrade-0.5-fixtures/generate.sh; do not edit by hand.\n'
}

wait_for() {
  for _ in $(seq 1 90); do
    if "$@" >/dev/null 2>&1; then return 0; fi
    sleep 1
  done
  echo "timed out waiting for: $*" >&2
  return 1
}

for backend in "${backends[@]}"; do
  case "$backend" in
    sqlite)
      "$generator" sqlite "sqlite://$work/fixture.db?mode=rwc" >"$out/sqlite.json"
      { header sqlite; sqlite3 "$work/fixture.db" .dump; } >"$out/sqlite.sql"
      ;;
    postgres)
      docker rm -f "$pg_container" >/dev/null 2>&1 || true
      docker run -d --name "$pg_container" -e POSTGRES_PASSWORD=fixture -e POSTGRES_DB=fixture \
        -p 127.0.0.1::5432 postgres:17 >/dev/null
      wait_for docker exec "$pg_container" pg_isready -U postgres -d fixture -h 127.0.0.1
      port="$(docker port "$pg_container" 5432/tcp | head -1 | sed 's/.*://')"
      "$generator" postgres "postgres://postgres:fixture@127.0.0.1:$port/fixture" >"$out/postgres.json"
      # Unqualified names, so the test can load the dump into any schema on its search_path.
      { header postgres
        docker exec "$pg_container" pg_dump -U postgres -d fixture --schema=public --no-owner \
          --no-privileges --no-comments --inserts \
          | grep -v -E '^CREATE SCHEMA public;|^\\(restrict|unrestrict)|^SELECT pg_catalog\.set_config|^SET |^--|^$' \
          | sed -E 's/\bpublic\.//g'
      } >"$out/postgres.sql"
      docker rm -f "$pg_container" >/dev/null
      ;;
    mysql)
      docker rm -f "$mysql_container" >/dev/null 2>&1 || true
      docker run -d --name "$mysql_container" -e MYSQL_ROOT_PASSWORD=fixture -e MYSQL_DATABASE=fixture \
        -p 127.0.0.1::3306 mysql:8.4 >/dev/null
      wait_for docker exec "$mysql_container" mysql -uroot -pfixture -h 127.0.0.1 -e 'SELECT 1' fixture
      port="$(docker port "$mysql_container" 3306/tcp | head -1 | sed 's/.*://')"
      "$generator" mysql "mysql://root:fixture@127.0.0.1:$port/fixture" >"$out/mysql.json"
      { header mysql
        echo 'SET FOREIGN_KEY_CHECKS = 0;'
        docker exec "$mysql_container" mysqldump -uroot -pfixture --compact --hex-blob \
          --skip-extended-insert --no-tablespaces --skip-triggers fixture 2>/dev/null \
          | grep -v -E '^/\*![0-9]+ SET '
        echo 'SET FOREIGN_KEY_CHECKS = 1;'
      } >"$out/mysql.sql"
      docker rm -f "$mysql_container" >/dev/null
      ;;
    *)
      echo "unknown backend: $backend (sqlite, postgres or mysql)" >&2
      exit 2
      ;;
  esac
  echo "wrote $out/$backend.sql and $out/$backend.json"
done
